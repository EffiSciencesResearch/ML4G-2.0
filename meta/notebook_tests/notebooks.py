def solution_notebooks() -> set[str]:
    """Paths of the workshop notebooks, minus the variants `notebook_tools sync` generates."""
    # Imported here: the Modal containers import this module without notebook_tools' deps.
    from meta.notebook_tools.helpers import generate_exercise_notebooks, load_notebook

    paths = {path.relative_to(ROOT).as_posix() for path in (ROOT / "workshops").rglob("*.ipynb")}
    variants = {
        path.removesuffix(".ipynb") + f"_{label}.ipynb"
        for path in paths
        for label in generate_exercise_notebooks(load_notebook(ROOT / path))
    }
    return paths - variants


def list_problems() -> list[str]:
    """What is wrong with TESTED and NOT_TESTED, as one sentence per problem."""
    notebooks = solution_notebooks()
    listed = set(TESTED) | NOT_TESTED.keys()
    problems = [
        f"{path} is in both TESTED and NOT_TESTED." for path in set(TESTED) & set(NOT_TESTED)
    ]
    problems += [
        f"{path} is listed but is not a solution notebook. Was it renamed or removed?"
        for path in sorted(listed - notebooks)
    ]
    problems += [
        f"{path} is new: add it to TESTED or NOT_TESTED in meta/notebook_tests/notebooks.py."
        for path in sorted(notebooks - listed)
    ]
    return problems
